// Current theme (can be changed via config)
export const currentTheme = 'default';

// Helper function to get current theme colors
export const getThemeColors = (themeName = currentTheme) => {
  return themeConfig[themeName] || themeConfig.default;
};

// Helper function to get CSS custom properties
export const getThemeCSSVariables = (themeName = currentTheme) => {
  const colors = getThemeColors(themeName);
  const variables = {};
  
  // Generate CSS variables for primary colors
  Object.entries(colors.primary).forEach(([shade, value]) => {
    variables[`--color-primary-${shade}`] = value;
  });
  
  // Generate CSS variables for secondary colors
  Object.entries(colors.secondary).forEach(([shade, value]) => {
    variables[`--color-secondary-${shade}`] = value;
  });
  
  return variables;
}; 